#define EX_MEDIA_QUEUE_MAX 32u

typedef struct ex_media_event {
  char *url;
  uint8_t *data;
  size_t len;
} ex_media_event;

static struct {
  const ccord_transport_vtable *orig_vt;
  ccord_transport_vtable patched;
  ccord_status (*orig_fetch)(ccord_transport *, const char *, ccord_error *);
  bool (*orig_poll)(ccord_transport *, ccord_net_event *);
  void (*orig_destroy)(ccord_transport *);
  char base[64];                       // "http://127.0.0.1:<port>" of the fake CDN
  ex_media_event queue[EX_MEDIA_QUEUE_MAX];
  size_t nqueue;
  ex_media_event pending;              // last event returned by poll(); freed on the next poll()
  size_t fetched;                      // loopback media fetches delivered
} ex_media;

static void ex_media_event_free(ex_media_event *ev)
{
  ccord_free(ev->url);
  ccord_free(ev->data);
  memset(ev, 0, sizeof *ev);
}

// Blocking HTTP/1.1 GET against the loopback fake CDN (Connection: close, bounded by poll timeouts).
static bool ex_http_get_bytes(const char *url, uint8_t *out, size_t cap, size_t *out_len)
{
  *out_len = 0;
  static const char k_loopback[] = "http://127.0.0.1:";
  if (strncmp(url, k_loopback, sizeof k_loopback - 1u) != 0) return false;
  char *end = nullptr;
  long port = strtol(url + (sizeof k_loopback - 1u), &end, 10);
  if (port <= 0 || port > 65535 || !end || *end != '/') return false;
  int fd = socket(AF_INET, SOCK_STREAM, 0);
  if (fd < 0) return false;
  struct sockaddr_in sin = {0};
  sin.sin_family = AF_INET;
  sin.sin_port = htons((uint16_t)port);
  sin.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
  if (connect(fd, (struct sockaddr *)&sin, sizeof sin) != 0) {
    close(fd);
    return false;
  }
  char req[600];
  int rn = snprintf(req, sizeof req, "GET %s HTTP/1.1\r\nHost: 127.0.0.1:%ld\r\nConnection: close\r\n\r\n",
                    end, port);
  bool ok = rn > 0 && (size_t)rn < sizeof req;
  size_t sent = 0;
  while (ok && sent < (size_t)rn) {
    ssize_t n = write(fd, req + sent, (size_t)rn - sent);
    if (n <= 0) ok = false;
    else sent += (size_t)n;
  }
  uint8_t buf[65536];
  size_t len = 0;
  while (ok && len + 1 < sizeof buf) {
    struct pollfd pfd = {.fd = fd, .events = POLLIN};
    int pr = poll(&pfd, 1, 3000);
    if (pr <= 0) break;
    ssize_t n = read(fd, buf + len, sizeof buf - 1 - len);
    if (n <= 0) break;
    len += (size_t)n;
  }
  close(fd);
  if (!ok || len == 0) return false;
  buf[len] = '\0';
  if (strncmp((char *)buf, "HTTP/1.1 200", 12) != 0) return false;
  char *body = strstr((char *)buf, "\r\n\r\n");
  if (!body) return false;
  body += 4;
  size_t blen = len - (size_t)(body - (char *)buf);
  if (blen == 0 || blen > cap) return false;
  memcpy(out, body, blen);
  *out_len = blen;
  return true;
}

static ccord_status ex_fetch_media(ccord_transport *t, const char *url, ccord_error *err)
{
  size_t blen = strlen(ex_media.base);
  bool fake = url && blen > 0 && strncmp(url, ex_media.base, blen) == 0 && url[blen] == '/';
  // Custom emoji tiles use hardcoded cdn.discordapp.com/emojis/<id> URLs (expression_picker.c). The
  // production allowlist admits that host, so without this the slice would hit the real network;
  // serve the fake PNG instead, keyed by the ORIGINAL url so the renderer texture lookup matches.
  bool emoji_cdn = url && strncmp(url, "https://cdn.discordapp.com/emojis/", 34) == 0;
  if (fake || emoji_cdn) {
    if (ex_media.nqueue >= EX_MEDIA_QUEUE_MAX) {
      return ccord_error_set(err, CCORD_ERR_IO, "verify: fake CDN media queue full");
    }
    char fetch_url[160];
    const char *get_url = url;
    if (emoji_cdn) {
      (void)snprintf(fetch_url, sizeof fetch_url, "%s/media/emoji.png", ex_media.base);
      get_url = fetch_url;
    }
    uint8_t buf[65536];
    size_t len = 0;
    if (!ex_http_get_bytes(get_url, buf, sizeof buf, &len)) {
      return ccord_error_set(err, CCORD_ERR_IO, "verify: fake CDN fetch failed");
    }
    ex_media_event *ev = &ex_media.queue[ex_media.nqueue++];
    ev->url = ccord_strndup(url, strlen(url));
    ev->data = ccord_alloc_array(len, 1);
    ev->len = len;
    if (!ev->url || !ev->data) {
      ex_media_event_free(ev);
      ex_media.nqueue--;
      return ccord_error_set(err, CCORD_ERR_NOMEM, "verify: out of memory");
    }
    memcpy(ev->data, buf, len);
    ex_media.fetched++;
    return CCORD_OK;
  }
  return ex_media.orig_fetch(t, url, err);   // production allowlist applies to everything else
}

static bool ex_poll(ccord_transport *t, ccord_net_event *out)
{
  ex_media_event_free(&ex_media.pending);   // the session copied the previous event during its pump
  if (ex_media.nqueue > 0) {
    ex_media.pending = ex_media.queue[0];
    memmove(&ex_media.queue[0], &ex_media.queue[1], (ex_media.nqueue - 1u) * sizeof ex_media.queue[0]);
    ex_media.nqueue--;
    memset(out, 0, sizeof *out);
    out->type = CCORD_NET_MEDIA_LOADED;
    out->status = CCORD_OK;
    out->media_url = ex_media.pending.url;
    out->media_data = ex_media.pending.data;
    out->media_len = ex_media.pending.len;
    out->media_path = "";
    return true;
  }
  return ex_media.orig_poll(t, out);
}

static void ex_destroy(ccord_transport *t)
{
  ex_media_event_free(&ex_media.pending);
  for (size_t i = 0; i < ex_media.nqueue; i++) ex_media_event_free(&ex_media.queue[i]);
  ex_media.nqueue = 0;
  ex_media.orig_destroy(t);
}

static void ex_media_install(ccord_transport *tr, const char *base)
{
  ex_media.orig_vt = tr->vt;
  ex_media.patched = *tr->vt;
  ex_media.orig_fetch = tr->vt->fetch_media;
  ex_media.orig_poll = tr->vt->poll;
  ex_media.orig_destroy = tr->vt->destroy;
  ex_media.patched.fetch_media = ex_fetch_media;
  ex_media.patched.poll = ex_poll;
  ex_media.patched.destroy = ex_destroy;
  (void)snprintf(ex_media.base, sizeof ex_media.base, "%s", base);
  tr->vt = &ex_media.patched;
}

// ---- input & pump helpers ----------------------------------------------------------------------------------

static fd_server *ex_http_server;
static fd_hit ex_hits[256];
static size_t ex_nhits;

// The fd child writes one fd_hit per request into a pipe the parent normally only drains at fd_stop.
// Drain it incrementally (records are <= PIPE_BUF, so writes are atomic) so a long slice can never
// block the child on a full pipe.
static void ex_drain_hits(void)
{
  if (!ex_http_server) return;
  for (;;) {
    fd_hit tmp;
    size_t got = 0;
    while (got < sizeof tmp) {
      ssize_t n = read(ex_http_server->pipe_rd, (char *)&tmp + got, sizeof tmp - got);
      if (n <= 0) break;
      got += (size_t)n;
    }
    if (got < sizeof tmp) break;
    if (ex_nhits < sizeof ex_hits / sizeof ex_hits[0]) ex_hits[ex_nhits++] = tmp;
  }
}

// One virtual frame + a real-time breather so the forked servers can answer.
static void ex_tick(void)
{
  ex_ctx->frames(ex_ctx->ud, 1);
  ex_sleep_ms(5);
  ex_drain_hits();
}

// Wheel notches glide: pump frames until the rail and grid offsets stop moving for three frames.
static void ex_settle_scroll(ccord_ui *ui)
{
  ui_expr_inspect prev, cur;
  int still = 0;
  if (!ui_expr_get_inspect(ui, &prev)) return;
  for (int i = 0; i < EX_WAIT_MAX && still < 3; i++) {
    ex_tick();
    if (!ui_expr_get_inspect(ui, &cur)) return;
    still = (cur.rail_scroll_y == prev.rail_scroll_y && cur.grid_scroll_y == prev.grid_scroll_y) ? still + 1 : 0;
    prev = cur;
  }
}

