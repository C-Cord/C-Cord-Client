// ---- kinds ---------------------------------------------------------------------------------------------------

typedef enum ev_expect : uint8_t { EV_PLAYS, EV_REFUSED, EV_UNDECODABLE } ev_expect;

typedef struct ev_kind {
  const char *name;
  ev_expect expect;
  int hit;                     // which hit of the message to click: 0 = first (play button / embed box), 1 = second
  const uint8_t *bytes;        // what the transport serves for `play_url`
  size_t len;
  int w, h;                    // size of the served clip
  const char *host;            // expected host in the player: warning
  const char *poster;          // a poster on the same host that is loaded without a click ("" = none)
  bool third_party;            // plays from a host outside the allow-list (only a click may fetch it)
  char play_url[2100];         // the URL the player must fetch (filled by build)
  char json[7000];             // the message as Discord sends it
  // observed
  unsigned fetched, refused, delivered;
  unsigned poster_fetched, poster_refused;   // the strict (automatic) fetch of `poster`
  uint8_t noise[4096];         // served instead of `bytes` for the undecodable kind (or with the corrupt switch)
  bool use_noise;
} ev_kind;

static ev_kind ev_kinds[9];
#define EV_NKINDS (sizeof ev_kinds / sizeof ev_kinds[0])

static const char *const ev_sig = "?ex=6740a1b2&is=673f5032&hm=8f3c2d1e9a7b6c5d4e3f2a1b0c9d8e7f6a5b4c3d2e1f0a9b8c7d6e5f4a3b2c1d&";
#define EV_CH "%llu"
#define EV_MSG_BASE 1500000000000000000ull

static void ev_noise(uint8_t *p, size_t n, uint32_t seed)
{
  uint32_t x = seed * 2654435761u + 12345u;
  for (size_t i = 0; i < n; i++) {
    x = x * 1664525u + 1013904223u;
    p[i] = (uint8_t)(x >> 24);
  }
}

static bool ev_attachment_msg(ev_kind *k, unsigned idx, unsigned long long chan, const char *url, const char *proxy,
                              size_t size)
{
  int n = snprintf(k->json, sizeof k->json,
                 "{\"id\":\"%llu\",\"channel_id\":\"" EV_CH "\",\"author\":{\"id\":\"1002\",\"username\":\"Ada\"},"
                 "\"content\":\"%s\",\"timestamp\":\"2025-01-01T00:00:%02u.000000+00:00\","
                 "\"attachments\":[{\"id\":\"%llu\",\"filename\":\"ccord_clip_%u.mp4\",\"content_type\":\"video/mp4\","
                 "\"size\":%zu,\"width\":%d,\"height\":%d,\"url\":\"%s\",\"proxy_url\":\"%s\"}],\"embeds\":[]}",
                 EV_MSG_BASE + idx, chan, k->name, idx, EV_MSG_BASE + 500u + idx, idx, size, k->w, k->h, url, proxy);
  return n >= 0 && (size_t)n < sizeof k->json;
}

static bool ev_embed_msg(ev_kind *k, unsigned idx, unsigned long long chan, const char *page, const char *provider,
                         const char *vurl, const char *vproxy, const char *thumb_proxy)
{
  int n = snprintf(k->json, sizeof k->json,
                 "{\"id\":\"%llu\",\"channel_id\":\"" EV_CH "\",\"author\":{\"id\":\"1003\",\"username\":\"Grace\"},"
                 "\"content\":\"%s\",\"timestamp\":\"2025-01-01T00:00:%02u.000000+00:00\",\"attachments\":[],"
                 "\"embeds\":[{\"type\":\"video\",\"url\":\"%s\",\"title\":\"clip %u\","
                 "\"provider\":{\"name\":\"%s\"},"
                 "\"thumbnail\":{\"url\":\"%s\",\"proxy_url\":\"%s\",\"width\":%d,\"height\":%d},"
                 "\"video\":{\"url\":\"%s\",\"proxy_url\":\"%s\",\"width\":%d,\"height\":%d}}]}",
                 EV_MSG_BASE + idx, chan, page, idx, page, idx, provider, thumb_proxy, thumb_proxy, k->w, k->h, vurl,
                 vproxy, k->w, k->h);
  return n >= 0 && (size_t)n < sizeof k->json;
}

static bool ev_build(unsigned long long chan)
{
  char url[2100], proxy[2100];
  ev_kind *k;
  unsigned i = 0;
  bool ok = true; // false when any URL or message JSON did not fit its buffer

  // 0. attachment, clicked on the picture box: the signed `url` is what plays.
  k = &ev_kinds[i];
  *k = (ev_kind){.name = "attachment-box", .expect = EV_PLAYS, .hit = 1, .bytes = ev_clip_a, .len = sizeof ev_clip_a,
                 .w = 200, .h = 150, .host = "cdn.discordapp.com"};
  (void)snprintf(url, sizeof url, "https://cdn.discordapp.com/attachments/1100000000000000001/1100000000000000011/"
                                  "ccord_clip_0.mp4%s", ev_sig);
  (void)snprintf(proxy, sizeof proxy, "https://media.discordapp.net/attachments/1100000000000000001/"
                                      "1100000000000000011/ccord_clip_0.mp4%s", ev_sig);
  (void)snprintf(k->play_url, sizeof k->play_url, "%s", url);
  ok &= ev_attachment_msg(k, i, chan, url, proxy, k->len);
  i++;

  // 1. attachment, clicked on its 24x24 play button.
  k = &ev_kinds[i];
  *k = (ev_kind){.name = "attachment-button", .expect = EV_PLAYS, .hit = 0, .bytes = ev_clip_b, .len = sizeof ev_clip_b,
                 .w = 160, .h = 90, .host = "cdn.discordapp.com"};
  (void)snprintf(url, sizeof url, "https://cdn.discordapp.com/attachments/1100000000000000001/1100000000000000012/"
                                  "ccord_clip_1.mp4%s", ev_sig);
  (void)snprintf(proxy, sizeof proxy, "https://media.discordapp.net/attachments/1100000000000000001/"
                                      "1100000000000000012/ccord_clip_1.mp4%s", ev_sig);
  (void)snprintf(k->play_url, sizeof k->play_url, "%s", url);
  ok &= ev_attachment_msg(k, i, chan, url, proxy, k->len);
  i++;

  // 2. native Discord embed of a Discord-hosted video link: plays video.proxy_url on media.discordapp.net.
  k = &ev_kinds[i];
  *k = (ev_kind){.name = "native-embed", .expect = EV_PLAYS, .hit = 0, .bytes = ev_clip_a, .len = sizeof ev_clip_a,
                 .w = 200, .h = 150, .host = "media.discordapp.net"};
  (void)snprintf(url, sizeof url, "https://cdn.discordapp.com/attachments/1100000000000000001/1100000000000000013/"
                                  "native_2.mp4%s", ev_sig);
  (void)snprintf(proxy, sizeof proxy, "https://media.discordapp.net/attachments/1100000000000000001/"
                                      "1100000000000000013/native_2.mp4%s", ev_sig);
  (void)snprintf(k->play_url, sizeof k->play_url, "%s", proxy);
  {
    char thumb[2100];
    (void)snprintf(thumb, sizeof thumb, "https://media.discordapp.net/attachments/1100000000000000001/"
                                        "1100000000000000013/native_2.png%s", ev_sig);
    ok &= ev_embed_msg(k, i, chan, url, "Discord", url, proxy, thumb);
  }
  i++;

  // 3. third-party embed: the site's video.url is not fetched; Discord's proxied copy is.
  k = &ev_kinds[i];
  *k = (ev_kind){.name = "third-party-embed", .expect = EV_PLAYS, .hit = 0, .bytes = ev_clip_b, .len = sizeof ev_clip_b,
                 .w = 160, .h = 90, .host = "images-ext-1.discordapp.net"};
  (void)snprintf(proxy, sizeof proxy, "https://images-ext-1.discordapp.net/external/Ab12Cd34Ef56Gh78/https/"
                                      "cdn.example.org/files/party_3.mp4");
  (void)snprintf(k->play_url, sizeof k->play_url, "%s", proxy);
  ok &= ev_embed_msg(k, i, chan, "https://example.org/watch/3", "Example", "https://cdn.example.org/files/party_3.mp4", proxy,
               "https://images-ext-1.discordapp.net/external/Ab12Cd34Ef56Gh78/https/cdn.example.org/files/party_3.jpg");
  i++;

  // 4. long signed URL (1024..2047 bytes: the parser keeps it, so the player must too).
  k = &ev_kinds[i];
  *k = (ev_kind){.name = "long-url", .expect = EV_PLAYS, .hit = 1, .bytes = ev_clip_a, .len = sizeof ev_clip_a,
                 .w = 200, .h = 150, .host = "cdn.discordapp.com"};
  {
    int n = snprintf(url, sizeof url, "https://cdn.discordapp.com/attachments/1100000000000000001/1100000000000000014/"
                                      "ccord_clip_4.mp4%sx=", ev_sig);
    for (; n < 1600; n++) url[n] = (char)('a' + n % 23);
    url[n] = '\0';
    int m = snprintf(proxy, sizeof proxy, "https://media.discordapp.net%s", url + strlen("https://cdn.discordapp.com"));
    ok &= m >= 0 && (size_t)m < sizeof proxy;
  }
  (void)snprintf(k->play_url, sizeof k->play_url, "%s", url);
  ok &= ev_attachment_msg(k, i, chan, url, proxy, k->len);
  i++;

  // 5. a third-party video on a host outside the allow-list, no proxied copy: only the click may fetch it. Its poster
  // sits on the same host and is loaded without a click, so it must stay refused by the strict gate.
  k = &ev_kinds[i];
  *k = (ev_kind){.name = "third-party-host", .expect = EV_PLAYS, .hit = 0, .bytes = ev_clip_b, .len = sizeof ev_clip_b,
                 .w = 160, .h = 90, .host = "videos.example.org", .third_party = true,
                 .poster = "https://videos.example.org/clip/poster_5.jpg"};
  (void)snprintf(url, sizeof url, "https://videos.example.org/clip/third_5.mp4?token=SECRETTOKEN123&sig=ZZ9");
  (void)snprintf(k->play_url, sizeof k->play_url, "%s", url);
  ok &= ev_embed_msg(k, i, chan, "https://videos.example.org/watch/5", "Example", url, "", k->poster);
  i++;

  // 6. bytes that are not a video: one warning from the decode stage.
  k = &ev_kinds[i];
  *k = (ev_kind){.name = "undecodable-body", .expect = EV_UNDECODABLE, .hit = 1, .bytes = ev_clip_a,
                 .len = sizeof ev_clip_a, .w = 200, .h = 150, .host = "cdn.discordapp.com", .use_noise = true};
  (void)snprintf(url, sizeof url, "https://cdn.discordapp.com/attachments/1100000000000000001/1100000000000000016/"
                                  "ccord_clip_6.mp4%s", ev_sig);
  (void)snprintf(proxy, sizeof proxy, "https://media.discordapp.net/attachments/1100000000000000001/"
                                      "1100000000000000016/ccord_clip_6.mp4%s", ev_sig);
  (void)snprintf(k->play_url, sizeof k->play_url, "%s", url);
  ok &= ev_attachment_msg(k, i, chan, url, proxy, 4096);
  i++;

  // 7. a clicked video over plain http: refused, one warning.
  k = &ev_kinds[i];
  *k = (ev_kind){.name = "refused-http", .expect = EV_REFUSED, .hit = 0, .bytes = ev_clip_b, .len = sizeof ev_clip_b,
                 .w = 160, .h = 90, .host = "videos.example.org"};
  (void)snprintf(url, sizeof url, "http://videos.example.org/clip/http_7.mp4?token=SECRETTOKEN123&sig=ZZ9");
  (void)snprintf(k->play_url, sizeof k->play_url, "%s", url);
  ok &= ev_embed_msg(k, i, chan, "https://videos.example.org/watch/7", "Example", url, "", "");
  i++;

  // 8. a clicked video on an IP-literal host: refused, one warning.
  k = &ev_kinds[i];
  *k = (ev_kind){.name = "refused-ip-literal", .expect = EV_REFUSED, .hit = 0, .bytes = ev_clip_b,
                 .len = sizeof ev_clip_b, .w = 160, .h = 90, .host = "203.0.113.5"};
  (void)snprintf(url, sizeof url, "https://203.0.113.5/clip/ip_8.mp4?token=SECRETTOKEN123&sig=ZZ9");
  (void)snprintf(k->play_url, sizeof k->play_url, "%s", url);
  ok &= ev_embed_msg(k, i, chan, "https://example.org/watch/8", "Example", url, "", "");
  i++;

  const char *corrupt = getenv("CCORD_VERIFY_EMBED_VIDEO_CORRUPT");
  for (size_t j = 0; j < EV_NKINDS; j++) {
    if (corrupt && strcmp(corrupt, ev_kinds[j].name) == 0) ev_kinds[j].use_noise = true;
    if (ev_kinds[j].use_noise) ev_noise(ev_kinds[j].noise, sizeof ev_kinds[j].noise, (uint32_t)j + 1u);
  }
  return ok;
}

// ---- transport wrapper ---------------------------------------------------------------------------------------

static const ccord_verify_embed_video_ctx *ev_ctx;
static unsigned ev_checks;
static bool ev_third_party_ok;

static struct {
  ccord_transport_vtable patched;
  ccord_status (*orig_fetch)(ccord_transport *, const char *, ccord_error *);
  bool (*orig_poll)(ccord_transport *, ccord_net_event *);
  ccord_live_event held;      // the injected message; the session copies it out during poll
  bool have_held, pending;
} ev_tr;

static ev_kind *ev_find(const char *url)
{
  if (!url) return nullptr;
  for (size_t i = 0; i < EV_NKINDS; i++) {
    if (ev_kinds[i].play_url[0] && strcmp(ev_kinds[i].play_url, url) == 0) return &ev_kinds[i];
  }
  return nullptr;
}

// Mirrors live_fetch_media_gated (live_transport.c): `user` is the click path (ccord_live_user_video_url_allowed),
// otherwise the strict allow-list that every automatic load keeps. A refusal happens before any request is made.
static ccord_status ev_fetch_gated(ccord_transport *t, const char *url, bool user, ccord_error *err)
{
  ev_kind *k = ev_find(url);
  bool ok = user ? ccord_live_user_video_url_allowed(url) : ccord_live_media_url_allowed(url);
  if (!user && url) {   // an automatic load of a kind's poster
    for (size_t i = 0; i < EV_NKINDS; i++) {
      if (ev_kinds[i].poster && ev_kinds[i].poster[0] && strcmp(ev_kinds[i].poster, url) == 0) {
        if (ok) ev_kinds[i].poster_fetched++;
        else ev_kinds[i].poster_refused++;
      }
    }
  }
  if (!ok) {
    if (k) k->refused++;
    return ccord_error_set(err, CCORD_ERR_PERMISSION, "live: media url blocked");
  }
  if (k) k->fetched++;
  return ev_tr.orig_fetch(t, url, err);
}

static ccord_status ev_fetch_media(ccord_transport *t, const char *url, ccord_error *err)
{
  return ev_fetch_gated(t, url, false, err);
}

static ccord_status ev_fetch_media_user(ccord_transport *t, const char *url, ccord_error *err)
{
  return ev_fetch_gated(t, url, true, err);
}

static bool ev_poll(ccord_transport *t, ccord_net_event *out)
{
  if (ev_tr.orig_poll(t, out)) {
    if (out->type == CCORD_NET_MEDIA_LOADED && out->status == CCORD_OK) {
      ev_kind *k = ev_find(out->media_url);
      if (k) {
        out->media_data = k->use_noise ? k->noise : k->bytes;
        out->media_len = k->use_noise ? sizeof k->noise : k->len;
        k->delivered++;
      }
    }
    return true;
  }
  if (ev_tr.pending) {
    ev_tr.pending = false;
    *out = ev_tr.held.ev;
    return true;
  }
  return false;
}

