static struct {
  unsigned n;                 // `player:` warnings since the last reset
  char line[4][320];
} ev_log;

static void ev_log_sink(ccord_log_level level, const char *line, void *ud)
{
  (void)ud;
  if (level == CCORD_LOG_WARN && strstr(line, "player:")) {
    if (ev_log.n < 4u) (void)snprintf(ev_log.line[ev_log.n], sizeof ev_log.line[0], "%s", line);
    ev_log.n++;
    return;
  }
  fprintf(stderr, "%s\n", line);
}

