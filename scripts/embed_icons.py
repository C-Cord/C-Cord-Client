#!/usr/bin/env python3
"""Regenerates src/platform/app_icon_data.c from assets/icons/*.png (stdlib only, deterministic)."""
import struct
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP_SIZES = [16, 22, 24, 32, 48, 64, 128, 256]
TRAY_SIZES = [22, 24, 32, 48]


def read_png(path):
    data = path.read_bytes()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise SystemExit(f"{path}: not a PNG")
    pos, idat, hdr = 8, b"", None
    while pos < len(data):
        n, typ = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + n]
        pos += 12 + n
        if typ == b"IHDR":
            hdr = struct.unpack(">IIBBBBB", body)
        elif typ == b"IDAT":
            idat += body
    w, h, depth, ctype, _, _, interlace = hdr
    if depth != 8 or ctype != 6 or interlace != 0:
        raise SystemExit(f"{path}: need 8-bit non-interlaced RGBA")
    raw = zlib.decompress(idat)
    stride = w * 4
    out = bytearray()
    prev = bytearray(stride)
    p = 0
    for _ in range(h):
        f = raw[p]
        line = bytearray(raw[p + 1:p + 1 + stride])
        p += 1 + stride
        for i in range(stride):
            a = line[i - 4] if i >= 4 else 0
            b = prev[i]
            c = prev[i - 4] if i >= 4 else 0
            if f == 1:
                line[i] = (line[i] + a) & 255
            elif f == 2:
                line[i] = (line[i] + b) & 255
            elif f == 3:
                line[i] = (line[i] + ((a + b) >> 1)) & 255
            elif f == 4:
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                pr = a if pa <= pb and pa <= pc else (b if pb <= pc else c)
                line[i] = (line[i] + pr) & 255
        out += line
        prev = line
    return w, h, bytes(out)


def emit(name, w, pix, lines):
    lines.append(f"static const uint8_t {name}[{len(pix)}] = {{")
    for i in range(0, len(pix), 24):
        lines.append("  " + ",".join(str(b) for b in pix[i:i + 24]) + ",")
    lines.append("};")


def main():
    lines = [
        "// SPDX-License-Identifier: AGPL-3.0-only WITH C-Cord-Extension-Exception",
        "// Copyright (C) 2026 C-Cord contributors — see LICENSE and LICENSES/C-Cord-Extension-Exception.txt",
        "// Generated by scripts/embed_icons.py from assets/icons/*.png. Do not edit.",
        '#include "app_icon_data.h"',
        "",
    ]
    for s in APP_SIZES:
        w, h, pix = read_png(ROOT / f"assets/icons/ccord-{s}.png")
        assert w == s and h == s
        emit(f"k_app_{s}", s, pix, lines)
    for s in TRAY_SIZES:
        w, h, pix = read_png(ROOT / f"assets/icons/ccord-tray-{s}.png")
        assert w == s and h == s
        emit(f"k_tray_{s}", s, pix, lines)
    lines.append("")
    lines.append("const ccord_icon_image ccord_app_icon_images[] = {")
    for s in APP_SIZES:
        lines.append(f"  {{{s}, k_app_{s}}},")
    lines.append("};")
    lines.append(f"const size_t ccord_app_icon_image_count = {len(APP_SIZES)};")
    lines.append("const ccord_icon_image ccord_tray_icon_images[] = {")
    for s in TRAY_SIZES:
        lines.append(f"  {{{s}, k_tray_{s}}},")
    lines.append("};")
    lines.append(f"const size_t ccord_tray_icon_image_count = {len(TRAY_SIZES)};")
    out = ROOT / "src/platform/app_icon_data.c"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
