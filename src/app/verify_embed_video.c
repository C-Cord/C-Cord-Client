static int ev_fail(const char *what)
{
  ccord_log_set_sink(nullptr, nullptr);
  ccord_log_set_level(CCORD_LOG_INFO);
  printf("embed-video: FAIL %s\n", what);
  fflush(stdout);
  return 1;
}

[[gnu::format(printf, 1, 2)]] static int ev_failf(const char *fmt, ...)
{
  char buf[500];
  va_list ap;
  va_start(ap, fmt);
  (void)vsnprintf(buf, sizeof buf, fmt, ap);
  va_end(ap);
  return ev_fail(buf);
}

static void ev_tick(int n) { ev_ctx->frames(ev_ctx->ud, n); }

static void ev_click(float x, float y)
{
  ccord_input_event ev = {.type = CCORD_IN_MOUSE_MOVE, .x = x, .y = y};
  ev_ctx->input(ev_ctx->ud, &ev);
  ev = (ccord_input_event){.type = CCORD_IN_MOUSE_DOWN, .button = 1, .clicks = 1, .x = x, .y = y};
  ev_ctx->input(ev_ctx->ud, &ev);
  ev = (ccord_input_event){.type = CCORD_IN_MOUSE_UP, .button = 1, .clicks = 1, .x = x, .y = y};
  ev_ctx->input(ev_ctx->ud, &ev);
}

// Media hits of the last frame whose URL is `url`, in the order the chat drew them.
static size_t ev_hits(const ccord_ui *ui, const char *url, const ui_media_hit **out, size_t cap)
{
  size_t n = 0;
  for (size_t i = 0; i < ui->nmedia_hits && n < cap; i++) {
    if (strcmp(ui->media_hits[i].url, url) == 0) out[n++] = &ui->media_hits[i];
  }
  return n;
}

static bool ev_inject(const char *json)
{
  if (ev_tr.have_held) ccord_live_event_free(&ev_tr.held);
  ev_tr.have_held = false;
  ccord_error err = {0};
  if (ccord_live_json_message(json, strlen(json), CCORD_NET_MESSAGE_CREATE, &ev_tr.held, &err) != CCORD_OK) {
    printf("embed-video: (parse) %s\n", err.message);
    return false;
  }
  ev_tr.have_held = true;
  ev_tr.pending = true;
  return true;
}

// ---- the slice -----------------------------------------------------------------------------------------------

int ccord_verify_embed_video_run(const ccord_verify_embed_video_ctx *ctx)
{
  if (!ctx || !ctx->session || !ctx->store || !ctx->ui || !ctx->renderer || !ctx->transport || !ctx->frames ||
      !ctx->input) {
    return ev_fail("invalid context");
  }
  ev_ctx = ctx;
  ccord_ui *ui = ctx->ui;
  ccord_renderer *r = ctx->renderer;

  ev_tr.orig_fetch = ctx->transport->vt->fetch_media;
  ev_tr.orig_poll = ctx->transport->vt->poll;
  ev_tr.patched = *ctx->transport->vt;
  ev_tr.patched.fetch_media = ev_fetch_media;
  ev_tr.patched.fetch_media_user = ev_fetch_media_user;
  ev_tr.patched.poll = ev_poll;
  ctx->transport->vt = &ev_tr.patched;

  ccord_id chan = CCORD_ID_NONE;
  for (int i = 0; i < 400 && chan == CCORD_ID_NONE; i++) {
    ev_tick(1);
    if (ccord_session_state(ctx->session) == CCORD_CONN_CONNECTED) chan = ccord_store_selected_channel(ctx->store);
  }
  if (chan == CCORD_ID_NONE) return ev_fail("setup: mock did not connect and select a channel");
  if (!ev_build((unsigned long long)chan)) return ev_fail("setup: a fixture URL or message did not fit its buffer");

  ccord_log_set_sink(ev_log_sink, nullptr);
  ccord_log_set_level(CCORD_LOG_WARN);

  for (size_t ki = 0; ki < EV_NKINDS; ki++) {
    ev_kind *k = &ev_kinds[ki];
    memset(&ev_log, 0, sizeof ev_log);

    // 1. The message arrives as Discord's JSON and is drawn: the video's hit-rect(s) exist.
    if (!ev_inject(k->json)) return ev_failf("%s: message JSON did not parse", k->name);
    const ui_media_hit *hits[4];
    size_t nh = 0;
    for (int i = 0; i < 120 && nh <= (size_t)k->hit; i++) {
      ev_tick(1);
      nh = ev_hits(ui, k->play_url, hits, 4);
    }
    if (nh <= (size_t)k->hit) {
      return ev_failf("hit-rect: %s has no click target for %s (%zu hit(s) with that URL; the URL was %zu bytes)",
                      k->name, k->play_url[0] ? "its video URL" : "?", nh, strlen(k->play_url));
    }
    ev_checks++;

    // 2. Click it through the real handler.
    ccord_rect rc = hits[k->hit]->play_rect;
    ev_click(rc.x + rc.w * 0.5f, rc.y + rc.h * 0.5f);

    if (k->expect == EV_REFUSED) {
      ev_tick(3);
      if (k->refused != 1u || k->fetched != 0u) {
        return ev_failf("refused: %s should be refused once before any request (refused=%u fetched=%u)", k->name,
                        k->refused, k->fetched);
      }
      if (!ui->media_failed) return ev_failf("refused: %s did not show as failed", k->name);
      ev_checks++;
    } else {
      // 3. Wait for the download and the first decoded frame.
      int tw = 0, th = 0;
      bool frame = false;
      for (int i = 0; i < 400 && !frame; i++) {
        ev_tick(1);
        if (k->expect == EV_UNDECODABLE && ui->media_failed) break;
        if (ui->media_loaded && ui->media_stream && strcmp(ui->media_url, k->play_url) == 0) {
          const ccord_av_info *inf = ccord_av_stream_info(ui->media_stream);
          frame = inf->w == k->w && inf->h == k->h && ccord_render_has_texture(r, EV_VIDEO_TEX_KEY, &tw, &th) &&
                  tw == k->w && th == k->h;
        }
      }
      if (k->expect == EV_PLAYS) {
        if (k->fetched == 0u) {
          return ev_failf("fetch: clicking %s never requested %s (refused=%u, media_failed=%d)", k->name, k->play_url,
                          k->refused, ui->media_failed ? 1 : 0);
        }
        if (k->delivered == 0u) return ev_failf("deliver: %s was requested but no bytes were delivered", k->name);
        if (ui->media_failed) {
          return ev_failf("open: %s delivered %zu bytes but the player gave up (%s)", k->name,
                          k->use_noise ? sizeof k->noise : k->len,
                          k->use_noise ? "random bytes were served" : "decoder refused the clip");
        }
        if (!frame) {
          int sw = ui->media_stream ? ccord_av_stream_info(ui->media_stream)->w : 0;
          int sh = ui->media_stream ? ccord_av_stream_info(ui->media_stream)->h : 0;
          return ev_failf("decode: %s has no first frame of the served %dx%d (stream %dx%d, texture %dx%d)", k->name,
                          k->w, k->h, sw, sh, tw, th);
        }
        ev_checks++;
        if (k->third_party) {
          // The click fetched a host outside the allow-list and it decoded to the served size; the same host's poster,
          // loaded without a click, was refused by the strict gate and never fetched.
          if (k->poster_fetched != 0u) {
            return ev_failf("auto: %s poster %s was fetched without a click (%u times)", k->name, k->poster,
                            k->poster_fetched);
          }
          if (k->poster_refused == 0u) {
            return ev_failf("auto: %s poster %s was never asked for, so the strict gate went unchecked", k->name,
                            k->poster);
          }
          if (ccord_live_media_url_allowed(k->play_url) || !ccord_live_user_video_url_allowed(k->play_url)) {
            return ev_failf("gate: %s must fail the strict gate and pass the click gate", k->name);
          }
          ev_checks += 2u;
          ev_third_party_ok = true;
        }
        // 4. It really plays: the playhead has moved off 0 (the clips are 1 s long, so it may already have ended).
        ev_tick(2);
        if (ui->media_pos_ms == 0u) {
          return ev_failf("playhead: %s decoded a frame but the playhead is stuck at 0 (playing=%d buffering=%d)",
                          k->name, ui->media_playing ? 1 : 0, ui->media_buffering ? 1 : 0);
        }
        ev_checks++;
      } else {
        if (!ui->media_failed || frame) {
          return ev_failf("open: %s served non-video bytes but the player did not refuse them (failed=%d frame=%d)",
                          k->name, ui->media_failed ? 1 : 0, frame ? 1 : 0);
        }
        ev_checks++;
      }
    }

    // 5. Warnings: a played video logs none; a failed stage logs exactly one `player:` line with stage and host and
    // no query string.
    if (k->expect == EV_PLAYS) {
      if (ev_log.n != 0u) return ev_failf("log: %s played but logged a player: warning: %s", k->name, ev_log.line[0]);
    } else {
      const char *stage = k->expect == EV_REFUSED ? "player: refused " : "player: decode ";
      if (ev_log.n != 1u) return ev_failf("log: %s expected exactly one player: warning, got %u", k->name, ev_log.n);
      char want_host[160];
      (void)snprintf(want_host, sizeof want_host, "host=%s", k->host);
      const char *ln = ev_log.line[0];
      if (!strstr(ln, stage) || !strstr(ln, want_host) || strcmp(strstr(ln, "host=") + strlen(want_host), "") != 0) {
        return ev_failf("log: %s warning does not name stage '%s' and '%s' at its end: %s", k->name, stage, want_host,
                        ln);
      }
      if (strchr(ln, '?') || strstr(ln, "ex=") || strstr(ln, "hm=") || strstr(ln, "token") || strstr(ln, "SECRET") ||
          strstr(ln, "/attachments") || strstr(ln, "/clip/")) {
        return ev_failf("log: %s warning leaks URL text beyond the host: %s", k->name, ln);
      }
      ev_checks++;
      printf("embed-video: %s logged: %s\n", k->name, ln);
    }
  }

  ccord_log_set_sink(nullptr, nullptr);
  ccord_log_set_level(CCORD_LOG_INFO);
  printf("embed_video_third_party_host_ok=%d\n", ev_third_party_ok ? 1 : 0);
  printf("embed-video: PASS checks=%u\n", ev_checks);
  fflush(stdout);
  return 0;
}
