"""Generate embedded fallback assets C source for single-binary C-Cord builds."""

import pathlib
import sys


def format_bytes(data: bytes) -> str:
    return ",".join(str(b) for b in data)


def main() -> int:
    if len(sys.argv) != 3:
        sys.stderr.write("usage: gen_embedded_assets.py <source_root> <out_c_path>\n")
        return 2

    root = pathlib.Path(sys.argv[1])
    out = pathlib.Path(sys.argv[2])

    t = (root / "assets/themes/c-cord-dark.theme").read_bytes()
    tl = (root / "assets/themes/c-cord-light.theme").read_bytes()
    ta = (root / "assets/themes/c-cord-amoled.theme").read_bytes()
    fr = (root / "assets/fonts/NotoSans-Regular.ttf").read_bytes()
    fb = (root / "assets/fonts/NotoSans-Bold.ttf").read_bytes()
    pj = (root / "extensions/copy-message-id/plugin.json").read_bytes()
    ml = (root / "extensions/copy-message-id/main.lua").read_bytes()

    code = (
        "// Generated by scripts/gen_embedded_assets.py — do not edit by hand.\n"
        "#include <ccord/assets/embedded_assets.h>\n"
        "#include <ccord/core/atomic_file.h>\n"
        "#include <stdio.h>\n"
        "#include <string.h>\n\n"
        f"static const unsigned char k_theme[] = {{{format_bytes(t)}, 0}};\n"
        f"static const unsigned char k_theme_light[] = {{{format_bytes(tl)}, 0}};\n"
        f"static const unsigned char k_theme_amoled[] = {{{format_bytes(ta)}, 0}};\n"
        f"static const unsigned char k_font_reg[] = {{{format_bytes(fr)}}};\n"
        f"static const unsigned char k_font_bold[] = {{{format_bytes(fb)}}};\n"
        f"static const unsigned char k_ext_json[] = {{{format_bytes(pj)}}};\n"
        f"static const unsigned char k_ext_lua[] = {{{format_bytes(ml)}}};\n\n"
        "const char *ccord_embedded_theme(size_t *out_len)\n"
        "{\n"
        "  if (out_len) *out_len = sizeof(k_theme) - 1;\n"
        "  return (const char *)k_theme;\n"
        "}\n\n"
        "const char *ccord_embedded_theme_by_id(const char *id, size_t *out_len)\n"
        "{\n"
        "  if (!id) return nullptr;\n"
        "  if (strcmp(id, \"c-cord-dark\") == 0) { if (out_len) *out_len = sizeof(k_theme) - 1; return (const char *)k_theme; }\n"
        "  if (strcmp(id, \"c-cord-light\") == 0) { if (out_len) *out_len = sizeof(k_theme_light) - 1; return (const char *)k_theme_light; }\n"
        "  if (strcmp(id, \"c-cord-amoled\") == 0) { if (out_len) *out_len = sizeof(k_theme_amoled) - 1; return (const char *)k_theme_amoled; }\n"
        "  return nullptr;\n"
        "}\n\n"
        "const unsigned char *ccord_embedded_font(const char *rel, size_t *out_len)\n"
        "{\n"
        "  if (!rel) return nullptr;\n"
        "  if (strstr(rel, \"Bold\") != nullptr) { if (out_len) *out_len = sizeof(k_font_bold); return k_font_bold; }\n"
        "  if (out_len) *out_len = sizeof(k_font_reg);\n"
        "  return k_font_reg;\n"
        "}\n\n"
        "static bool write_blob(const char *path, const unsigned char *data, size_t len)\n"
        "{\n"
        "  FILE *fp = fopen(path, \"wb\");\n"
        "  if (!fp) return false;\n"
        "  bool ok = fwrite(data, 1, len, fp) == len;\n"
        "  fclose(fp);\n"
        "  return ok;\n"
        "}\n\n"
        "bool ccord_embedded_materialize_extensions(const char *dest_dir)\n"
        "{\n"
        "  if (!dest_dir || !dest_dir[0]) return false;\n"
        "  ccord_error err;\n"
        "  if (ccord_mkdir_p(dest_dir, 0700, &err) != CCORD_OK) return false;\n"
        "  char sub[4096], p1[4096], p2[4096];\n"
        "  if ((size_t)snprintf(sub, sizeof sub, \"%s/copy-message-id\", dest_dir) >= sizeof sub) return false;\n"
        "  if (ccord_mkdir_p(sub, 0700, &err) != CCORD_OK) return false;\n"
        "  if ((size_t)snprintf(p1, sizeof p1, \"%s/plugin.json\", sub) >= sizeof p1) return false;\n"
        "  if ((size_t)snprintf(p2, sizeof p2, \"%s/main.lua\", sub) >= sizeof p2) return false;\n"
        "  return write_blob(p1, k_ext_json, sizeof k_ext_json) && write_blob(p2, k_ext_lua, sizeof k_ext_lua);\n"
        "}\n"
    )
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(code, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
