// Binary-safe response (fd_reply is JSON/text only; the icon body is raw PNG bytes).
static size_t ex_reply_bytes(char *out, size_t cap, int status, const char *reason, const char *ctype,
                             const uint8_t *body, size_t len)
{
  int n = snprintf(out, cap, "HTTP/1.1 %d %s\r\nContent-Type: %s\r\nContent-Length: %zu\r\nConnection: close\r\n\r\n",
                   status, reason, ctype, len);
  if (n <= 0 || (size_t)n >= cap || (size_t)n + len > cap) return 0;
  memcpy(out + n, body, len);
  return (size_t)n + len;
}

// Minimal protobuf writer (same wire shape as src/session/tests/test_session.c): FrecencyUserSettings
// root field 2 = favorite_gifs { repeated field 1 = entry { 1: url, 2: gif { 2: src, 3: w, 4: h, 5: fmt } } }.
static size_t ex_pb_varint(uint8_t *p, uint64_t v)
{
  size_t n = 0;
  do {
    p[n] = (uint8_t)((v & 0x7fu) | (v > 0x7fu ? 0x80u : 0u));
    v >>= 7;
    n++;
  } while (v != 0);
  return n;
}

static size_t ex_pb_bytes(uint8_t *p, unsigned field, const void *data, size_t len)
{
  size_t n = ex_pb_varint(p, ((uint64_t)field << 3u) | 2u);
  n += ex_pb_varint(p + n, len);
  memcpy(p + n, data, len);
  return n + len;
}

static size_t ex_pb_uint(uint8_t *p, unsigned field, uint64_t v)
{
  size_t n = ex_pb_varint(p, (uint64_t)field << 3u);
  return n + ex_pb_varint(p + n, v);
}

static size_t ex_b64(const uint8_t *in, size_t len, char *out)
{
  static const char tbl[] = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
  size_t o = 0, i = 0;
  for (; i + 2 < len; i += 3) {
    uint32_t v = ((uint32_t)in[i] << 16u) | ((uint32_t)in[i + 1] << 8u) | in[i + 2];
    out[o++] = tbl[(v >> 18u) & 63u];
    out[o++] = tbl[(v >> 12u) & 63u];
    out[o++] = tbl[(v >> 6u) & 63u];
    out[o++] = tbl[v & 63u];
  }
  if (i < len) {
    uint32_t v = (uint32_t)in[i] << 16u;
    if (i + 1 < len) v |= (uint32_t)in[i + 1] << 8u;
    out[o++] = tbl[(v >> 18u) & 63u];
    out[o++] = tbl[(v >> 12u) & 63u];
    out[o++] = i + 1 < len ? tbl[(v >> 6u) & 63u] : '=';
    out[o++] = '=';
  }
  out[o] = '\0';
  return o;
}

// One favorite GIF entry: page url + media src on the fake CDN + dimensions.
// Gif value fields (discord_proto.c parse_gif_value): 1 format, 2 src, 3 width, 4 height, 5 order.
static size_t ex_settings_entry(uint8_t *out, int port, int idx, const char *url, uint32_t w, uint32_t h)
{
  char src[160];
  (void)snprintf(src, sizeof src, "http://127.0.0.1:%d/media/fav-%d.gif", port, idx);
  uint8_t gif[256];
  size_t gn = 0;
  gn += ex_pb_uint(gif + gn, 1, 1);
  gn += ex_pb_bytes(gif + gn, 2, src, strlen(src));
  gn += ex_pb_uint(gif + gn, 3, w);
  gn += ex_pb_uint(gif + gn, 4, h);
  gn += ex_pb_uint(gif + gn, 5, (uint32_t)idx);
  size_t en = 0;
  en += ex_pb_bytes(out + en, 1, url, strlen(url));
  en += ex_pb_bytes(out + en, 2, gif, gn);
  return en;
}

